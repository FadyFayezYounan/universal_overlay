/// Position options for overlays on screen.
enum OverlayPosition {
  /// Top center of the screen
  top,

  /// Top left corner
  topLeft,

  /// Top right corner
  topRight,

  /// Center of the screen
  center,

  /// Center left
  centerLeft,

  /// Center right
  centerRight,

  /// Bottom center of the screen
  bottom,

  /// Bottom left corner
  bottomLeft,

  /// Bottom right corner
  bottomRight,
}
